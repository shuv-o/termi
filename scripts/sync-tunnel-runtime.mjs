#!/usr/bin/env node
/**
 * Copy the tunnel client runtime from the desktop app into the web app, which
 * embeds it in downloadable bridge scripts. apps/electron/tunnel-mux.js is the
 * source of truth; runtime-source.test.ts fails when the copy is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const src = readFileSync(`${root}apps/electron/tunnel-mux.js`, 'utf8');
const match = src.match(/\/\/ ── RUNTIME START ──\n([\s\S]*?)\/\/ ── RUNTIME END ──/);
if (!match) throw new Error('RUNTIME markers not found in apps/electron/tunnel-mux.js');

writeFileSync(
    `${root}apps/web/src/lib/tunnel/runtime-source.ts`,
    `// GENERATED by scripts/sync-tunnel-runtime.mjs from apps/electron/tunnel-mux.js.
// Do not edit: change tunnel-mux.js and run \`npm run sync:tunnel-runtime\`.
export const TUNNEL_RUNTIME_SOURCE = ${JSON.stringify(match[1])};
`,
);
console.log('apps/web/src/lib/tunnel/runtime-source.ts updated');
